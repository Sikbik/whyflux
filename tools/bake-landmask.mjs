#!/usr/bin/env node
// Bakes a compact equirectangular land mask for the dot-matrix globe.
//
//   node tools/bake-landmask.mjs <land-110m.json> [width=720]
//
// Input: a Natural Earth "land" TopoJSON (public domain), as shipped by Flux Atlas at
// web/public/data/land-110m.json. Output: src/lib/globe/landmask.generated.ts, a run-length
// encoded 0.5 degree mask (width x width/2 cells), about 9 KB of base64. The globe samples it to
// place land dots, and the procedural fallback uses it to keep illustrative nodes on land.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [input, wArg] = process.argv.slice(2);
if (!input) {
  console.error('usage: node tools/bake-landmask.mjs <land-110m.json> [width]');
  process.exit(2);
}
const W = Number(wArg ?? 720);
const H = W / 2;

const topo = JSON.parse(readFileSync(resolve(input), 'utf8'));
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;

// Decode the quantised, delta-encoded arcs to lon/lat.
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * sx + tx, y * sy + ty];
  });
});

function ring(indices) {
  const pts = [];
  for (const i of indices) {
    const a = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    for (let k = pts.length ? 1 : 0; k < a.length; k++) pts.push(a[k]);
  }
  return pts;
}

const polygons = [];
for (const g of Object.values(topo.objects)) {
  const geoms = g.type === 'GeometryCollection' ? g.geometries : [g];
  for (const geom of geoms) {
    const list = geom.type === 'MultiPolygon' ? geom.arcs : geom.type === 'Polygon' ? [geom.arcs] : [];
    for (const poly of list) polygons.push(poly.map(ring));
  }
}

const mask = new Uint8Array(W * H);
for (let j = 0; j < H; j++) {
  const lat = 90 - ((j + 0.5) * 180) / H;
  for (const rings of polygons) {
    const xs = [];
    for (const r of rings) {
      for (let k = 0; k < r.length - 1; k++) {
        const [x1, y1] = r[k];
        const [x2, y2] = r[k + 1];
        if ((y1 <= lat && y2 > lat) || (y2 <= lat && y1 > lat)) {
          xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
        }
      }
    }
    xs.sort((a, b) => a - b);
    for (let n = 0; n + 1 < xs.length; n += 2) {
      const c0 = Math.max(0, Math.ceil(((xs[n] + 180) * W) / 360 - 0.5));
      const c1 = Math.min(W - 1, Math.floor(((xs[n + 1] + 180) * W) / 360 - 0.5));
      for (let c = c0; c <= c1; c++) mask[j * W + c] = 1;
    }
  }
}

// Run-length encode each row: [runCount, run0 (water), run1 (land), ...] as little-endian uint16.
const out = [];
let land = 0;
for (let j = 0; j < H; j++) {
  const runs = [];
  let cur = 0;
  let len = 0;
  for (let c = 0; c < W; c++) {
    const v = mask[j * W + c];
    land += v;
    if (v === cur) len++;
    else {
      runs.push(len);
      cur = v;
      len = 1;
    }
  }
  runs.push(len);
  out.push(runs.length, ...runs);
}
const bytes = Buffer.from(new Uint8Array(new Uint16Array(out).buffer));
const b64 = bytes.toString('base64');

const ts = `/**
 * GENERATED by tools/bake-landmask.mjs from Natural Earth land (public domain). Do not edit.
 * A ${W} x ${H} equirectangular land mask (${360 / W} degrees per cell), run-length encoded per row:
 * [runs, water, land, water, ...] as little-endian uint16, base64. ${land} land cells.
 */
export const LAND_W = ${W};
export const LAND_H = ${H};
export const LAND_RLE = '${b64}';
`;
writeFileSync(resolve('src/lib/globe/landmask.generated.ts'), ts);
console.log(`landmask: ${W}x${H}, ${land} land cells (${((land / (W * H)) * 100).toFixed(1)}%), ${b64.length} base64 chars`);
